"""F-230: facial-hair textures for hair colours that have a facial-hair row but no texture.

Undead male (REUSE): its facial-hair textures are the jaw skins, the same file at every hair colour; an empty row
gets the colour-0 row's files unchanged.

Mod 907 (mod907_import.py) added draenei male hair colours 10-21 with CharSections facial-hair rows (base_section 2,
types 2-6) whose textures are empty: on those colours the painted whiskers under the geoset slots disappear. Each
missing texture is made from the same style at the stock colour whose hair texture maps best onto the new colour's
(a quadratic RGB fit, hair texture to hair texture: they are recolours of one layout), run through that fit. Alpha
is kept as painted.

The rows mod907_import.py wrote stay as they are (its output is generated); this script writes OVERRIDE rows for the
same keys at higher ids (the source client takes the highest id of a key, F-225) and the textures:

  zpaks/zep-skin-expansion/dbc/[F-230]_charsections_facialhair_colours.sql   ids from ID_BASE
  zpaks/zep-skin-expansion/mpq/source-assets/Character/<Race>/<Sex>/FacialLowerHairNN_zC.blp (+ Upper), and their
  parsed-assets copies (the skin check reads parsed-assets)

  python3 "Scripts/Character Skins/facial_hair_colours.py" [--sheet out.png]
"""
import argparse
import importlib.util
import sys
from pathlib import Path

import numpy as np
from PIL import Image

CRAFT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(CRAFT / 'cli'))
sys.path.insert(0, str(CRAFT))
from lib.wardrobe.blp import read_blp  # noqa: E402

HERE = Path(__file__).resolve().parent


def _load(name):
    spec = importlib.util.spec_from_file_location(name, HERE / f'{name}.py')
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


ZPAK = CRAFT / 'zpaks' / 'zep-skin-expansion'
ASSETS = ZPAK / 'mpq' / 'source-assets'
PARSED = ZPAK / 'mpq' / 'parsed-assets'
SQL = ZPAK / 'dbc' / '[F-230]_charsections_facialhair_colours.sql'
ID_BASE = 104000                  # 104000-104999: this script
ID_END = 104999
TARGETS = [(11, 0), (5, 0)]       # race, sex (night elf female rows of this kind belong to other work)
# race, sex whose facial-hair textures are not hair-coloured: an empty row takes the textures of the same style at
# colour 0 (the lowest colour with any) as they are. Undead male: the "facial hair" is the jaw skin of the jaw its row
# shapes (F-230 Jaw button); mod 907's hair colour 10 has empty rows, so on that colour the jaw lost its skin
REUSE = {(5, 0)}


def query(sql):
    """Rows as dicts from the live DBC database (the CLI's text output escapes backslashes)."""
    from commands.wardrobe import _dbc_query_fn
    global _q
    if _q is None:
        _q = _dbc_query_fn('live')
    return [{k: (str(v) if v is not None else '') for k, v in r.items()} for r in _q(sql)]


_q = None


def esc(s):
    return s.replace('\\', '\\\\').replace("'", "''")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--sheet', help='write a contact sheet of every made texture (source | made) here')
    a = ap.parse_args()
    spv = _load('skin_preview')
    feats = _load('gnome_female_extra_skins').feats
    write_blp_rgba = _load('subrace_icons').write_blp_rgba
    files = spv.files_resolver()

    def img(path):
        f = files.find(path) if path else None
        return read_blp(f).convert('RGBA') if f else None

    sql = ['-- F-230: facial-hair textures for hair colours whose facial-hair row has none (mod 907 rows, see',
           '-- Scripts/Character Skins/facial_hair_colours.py). Override rows: same key, higher id than the empty row.',
           '-- GENERATED by Scripts/Character Skins/facial_hair_colours.py - do not edit, re-run the script.',
           f'DELETE FROM charsections WHERE id BETWEEN {ID_BASE} AND {ID_END};',
           'INSERT INTO charsections (id, race, gender, base_section, texture_1, texture_2, texture_3, flags, type, '
           'color_index) VALUES']
    vals, sheet, rid = [], [], ID_BASE
    for race, sex in TARGETS:
        rows = query(f'SELECT id, type, color_index, texture_1, texture_2, flags FROM charsections WHERE race = {race} '
                     f'AND gender = {sex} AND base_section = 2 AND id < {ID_BASE} ORDER BY id')
        top = {}
        for r in rows:
            top[(int(r['type']), int(r['color_index']))] = r          # highest id wins, as in the client
        hair = {int(r['color_index']): r['texture_1'] for r in
                query(f'SELECT color_index, texture_1 FROM charsections WHERE race = {race} AND gender = {sex} '
                      f'AND base_section = 3 AND type = 0 ORDER BY id')}
        styles = sorted({t for (t, c), r in top.items() if r['texture_1'] or r['texture_2']})
        for t in styles:
            have = {c for (tt, c), r in top.items() if tt == t and (r['texture_1'] or r['texture_2'])}
            empty = sorted(c for (tt, c), r in top.items() if tt == t and not (r['texture_1'] or r['texture_2']))
            for c in empty:
                if (race, sex) in REUSE:
                    s = min(have)
                    src = top[(t, s)]
                    vals.append(f"({rid}, {race}, {sex}, 2, '{esc(src['texture_1'])}', '{esc(src['texture_2'])}', '', "
                                f"{top[(t, c)]['flags']}, {t}, {c})")
                    print(f'{race}/{sex} style {t} colour {c}: colour {s} textures as they are -> id {rid}')
                    rid += 1
                    continue
                dst_hair = img(hair.get(c))
                if dst_hair is None:
                    print(f'{race}/{sex} style {t} colour {c}: no hair texture, skipped')
                    continue
                best = None
                for s in sorted(have):
                    src_hair = img(hair.get(s))
                    if src_hair is None:
                        continue
                    A = np.asarray(src_hair.convert('RGB').resize(dst_hair.size, Image.LANCZOS)).reshape(-1, 3).astype(float)
                    B = np.asarray(dst_hair.convert('RGB')).reshape(-1, 3).astype(float)
                    w, *_ = np.linalg.lstsq(feats(A), B, rcond=None)
                    err = np.abs(feats(A) @ w - B).mean()
                    if best is None or err < best[0]:
                        best = (err, s, w)
                err, s, w = best
                src = top[(t, s)]
                made = {}
                for col, kind in (('texture_1', 'Lower'), ('texture_2', 'Upper')):
                    im = img(src[col])
                    if im is None:
                        made[col] = ''
                        continue
                    arr = np.asarray(im).astype(float)
                    rgb = np.clip(feats(arr[..., :3]) @ w, 0, 255)
                    out = Image.fromarray(np.dstack([rgb, arr[..., 3]]).astype(np.uint8), 'RGBA')
                    stem = src[col].rsplit('\\', 1)[-1].rsplit('_', 1)[0]          # FacialLowerHair01
                    rel = src[col].rsplit('\\', 1)[0] + f'\\{stem}_z{c}.blp'
                    write_blp_rgba(ASSETS / rel.replace('\\', '/'), out)
                    dst = PARSED / rel.replace('\\', '/').upper()
                    dst.parent.mkdir(parents=True, exist_ok=True)
                    dst.write_bytes((ASSETS / rel.replace('\\', '/')).read_bytes())
                    made[col] = rel
                    sheet.append((im, out))
                if rid > ID_END:
                    sys.exit('id range full')
                vals.append(f"({rid}, {race}, {sex}, 2, '{esc(made['texture_1'])}', '{esc(made['texture_2'])}', '', "
                            f"{top[(t, c)]['flags']}, {t}, {c})")
                print(f'{race}/{sex} style {t} colour {c}: from colour {s} (fit error {err:.1f}) -> id {rid}')
                rid += 1
    SQL.write_text('\n'.join(sql) + '\n' + ',\n'.join(vals) + ';\n')
    print(f'wrote {SQL} ({len(vals)} rows)')
    if a.sheet and sheet:
        cell = 256
        S = Image.new('RGBA', (cell * 4, cell // 2 * ((len(sheet) + 1) // 2)), (90, 90, 120, 255))
        for i, (x, y) in enumerate(sheet):
            for j, im in enumerate((x, y)):
                t = im.resize((cell, cell // 2))
                S.alpha_composite(t, ((i % 2) * 2 * cell + j * cell, (i // 2) * (cell // 2)))
        S.save(a.sheet)
        print(f'sheet: {a.sheet}')


if __name__ == '__main__':
    main()
