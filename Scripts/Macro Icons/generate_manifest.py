#!/usr/bin/env python3
"""
F-181 Custom Macro Icons - manifest generator.

Generates ZeppelinMacroIcons.lua, a flat list of every distinct SpellIcon.dbc
path under Interface\\Icons\\. The overridden Blizzard_MacroUI addon feeds the
macro icon picker from this list instead of the client's baked-in (and
non-extendable) GetNumMacroIcons list.

Re-run after adding/removing spell icons:
    python3 "Scripts/Macro Icons/generate_manifest.py"
"""
import re
import subprocess
import sys
from pathlib import Path

CRAFT_ROOT = Path(__file__).resolve().parents[2]
OUT = (CRAFT_ROOT / "zpaks" / "patch-custom-icons" / "mpq" / "source-assets"
       / "Interface" / "AddOns" / "Blizzard_MacroUI" / "ZeppelinMacroIcons.lua")

QUERY = "SELECT DISTINCT name FROM spellicon WHERE name <> '' ORDER BY name"


def fetch_paths():
    res = subprocess.run(
        [sys.executable, "-m", "cli.zep", "dbc", "info", "query", QUERY],
        cwd=CRAFT_ROOT, capture_output=True, text=True,
    )
    if res.returncode != 0:
        sys.exit(f"DBC query failed:\n{res.stderr}")
    paths = []
    seen = set()
    for line in res.stdout.splitlines():
        line = line.strip()
        if not line or line == "name" or line.lower().startswith("running query"):
            continue
        # DB stores doubled backslashes; collapse runs to a single separator.
        norm = re.sub(r"\\+", "\\\\", line)
        if not norm.lower().startswith("interface\\icons\\"):
            continue  # skip Spellbook/Spells entries - not square icons
        key = norm.lower()
        if key in seen:
            continue
        seen.add(key)
        paths.append(norm)
    return paths


def main():
    paths = fetch_paths()
    if not paths:
        sys.exit("No SpellIcon paths found - aborting (refusing to write empty manifest).")
    lines = ["-- AUTO-GENERATED by Scripts/Macro Icons/generate_manifest.py (F-181).",
             "-- Do not edit by hand. Source: SpellIcon.dbc (Interface\\\\Icons\\\\ paths).",
             f"-- {len(paths)} icons.",
             "ZeppelinMacroIcons = {"]
    for p in paths:
        lua = p.replace("\\", "\\\\")  # escape backslashes for the Lua literal
        lines.append(f'\t"{lua}",')
    lines.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(paths)} icons -> {OUT}")


if __name__ == "__main__":
    main()
