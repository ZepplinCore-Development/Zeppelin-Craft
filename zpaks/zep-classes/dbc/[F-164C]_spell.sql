-- ============================================================================
-- Child of F-164 (Earthwarden). F-164 retains the Earthwarden skillline + talent-
-- tree structure; this file owns the Rockbiter / Improved Rockbiter spell records.
--
-- Rockbiter is a weapon imbue that grants Strength (aura 29 MOD_STAT) + threat
-- (aura 10 MOD_THREAT). Cast imbue -> C++ damage-switch (shared core patch 0017,
-- still owned by F-164) -> enchant-spell -> SpellItemEnchantment -> per-rank
-- passive (below). Improved Rockbiter (talent 2930) boosts the passive via
-- SpellMod targeting its unique spell_class_mask_3 = 128.
--
-- BALANCE (2026-06-26): Strength rebalanced to match the Strength of Earth Totem
-- (STR+AGI) sum at each rank's learn level, snapped to multiples of 10 so the
-- Improved Rockbiter +10/20/30% modifier always resolves to a whole number.
-- Displayed STR = effect_base_points_1 + 1 (die_sides = 1 convention).
--   Rank:  R1 R2 R3 R4 R5 R6  R7  R8  R9  R10
--   Level:  1  8 16 24 34 44  54  62  70   78
--   STR:   10 20 30 40 60 90 130 160 200  280
-- ============================================================================

