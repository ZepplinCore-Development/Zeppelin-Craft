#!/usr/bin/env python3
"""Zeppelin F-223A: build Zeppelin\\LampCatalog.txt (PATCH-V) from scan.tsv (scan_lamps.py).

One line per world model that looks like a light source but carries no M2 light of its own:
    path|x|y|z|r|g|b|flags
x y z: where the light sits, in model space (the particle emitters' centre, else from the bounds);
r g b: colour * intensity on the client's own scale (CM2Light::m_dirColor: stock fires 0.47 0.29 0.13);
flags: f = flickers (flames).  Written from the stock client's own files and lights.
"""
import csv, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'mpq', 'source-assets', 'Zeppelin', 'LampCatalog.txt')

OFF = re.compile(r'nolight|particle|(^|[_\\-])off([_\d.]|$)|onoff|unlit|nofire|noflame|extinguish|burnt|burned|cold|broken|destroyed|'
                 r'ruined|dead_?|skeleton', re.I)
# Kind by name, first match wins: (pattern, kind, base colour, flicker)
FIRE = (0.47, 0.29, 0.13)          # the stock fires, braziers and firepits
CANDLE = (0.42, 0.29, 0.14)
LAMP = (0.62, 0.48, 0.26)          # classic oil lamps and lanterns: warm, a little whiter than fire
KINDS = [
    (r'chandelier|candelabra', 'chandelier', CANDLE, True, 1.2),
    (r'candle', 'candle', CANDLE, True, 0.45),
    (r'bonfire|largefire|bigfire', 'bonfire', FIRE, True, 1.6),
    (r'campfire|firepit|fire_?pit|cookfire|cooking', 'campfire', FIRE, True, 1.1),
    (r'brazier', 'brazier', FIRE, True, 1.0),
    (r'fireplace|hearth|furnace|forge|oven|kiln|smelter', 'hearth', FIRE, True, 1.0),
    (r'torch', 'torch', FIRE, True, 0.8),
    (r'sconce', 'sconce', FIRE, True, 0.7),
    (r'lamppost|lamp_?post|streetlamp|streetlight|lightpost|light_?post', 'lamppost', LAMP, False, 1.0),
    (r'lantern', 'lantern', LAMP, False, 0.75),
    (r'lamp', 'lamp', LAMP, False, 0.8),
    (r'fire', 'fire', FIRE, True, 1.0),
]
TINTS = [  # colour words in the path or the particle textures override the base colour (stock coloured lights)
    (r'fel|green|plague|poison|slime', (0.10, 0.75, 0.25)),
    (r'blue|frost|ice|arcane|cyan|azure', (0.13, 0.45, 0.95)),
    (r'purple|violet|shadow|void|nether', (0.60, 0.15, 0.90)),
    (r'red(?![a-z])|blood', (0.95, 0.12, 0.05)),
    (r'yellow|gold', (0.90, 0.80, 0.20)),
]

def classify(r):
    path = r['path']
    name = path.split('\\')[-1]  # backslash paths: os.path.basename would keep the directories
    if OFF.search(name):
        return None
    # Place names are not light sources: Hellfire (Citadel, Peninsula) and the Exodar's crystal forge.
    plain = re.sub(r'hellfire|crystalforge|fireworks?', '', name, flags=re.I)
    for pat, kind, colour, flicker, scale in KINDS:
        if re.search(pat, plain, re.I):
            break
    else:
        return None
    emitters = int(r['emitters'])
    # Flames need their particles: a "fire" or brazier model with none is unlit (or a fire-themed prop).
    if flicker and emitters == 0 and kind not in ('chandelier', 'candle', 'sconce', 'torch'):
        return None
    # The model's own file name only, colour words starting a word (felbrazier, bt_brazier_blue): directories and
    # texture paths gave false tints (Goldshire -> gold, DEVICES -> ice).
    for pat, tint in TINTS:
        if re.search(r'(?<![a-z])(' + pat + ')', name, re.I):
            colour = tint
            break
    rgb = tuple(c * scale for c in colour)
    mn = [float(r[k]) for k in ('minx', 'miny', 'minz')]
    mx = [float(r[k]) for k in ('maxx', 'maxy', 'maxz')]
    if any(abs(v) > 1000 for v in mn + mx) or mx[2] <= mn[2]:
        return None
    if emitters and r['cx'] != '':
        pos = [float(r['cx']), float(r['cy']), float(r['cz'])]
        # an emitter centre outside the bounds is a bone-relative position: fall back to the bounds
        if not all(mn[i] - 1 <= pos[i] <= mx[i] + 1 for i in range(3)):
            pos = None
    else:
        pos = None
    if pos is None:
        h = mx[2] - mn[2]
        w = max(mx[0] - mn[0], mx[1] - mn[1])
        top = 0.88 if (kind == 'lamppost' or h > 2.5 * w) else 0.6
        pos = [(mn[0] + mx[0]) / 2, (mn[1] + mx[1]) / 2, mn[2] + top * h]
    return pos, rgb, 'f' if flicker else ''

rows = list(csv.DictReader(open(os.path.join(HERE, 'scan.tsv')), delimiter='\t'))
lines, kinds = [], {}
for r in rows:
    if int(r['lights']) > 0:
        continue                       # the model lights itself
    c = classify(r)
    if not c:
        continue
    pos, rgb, flags = c
    lines.append('%s|%.2f|%.2f|%.2f|%.3f|%.3f|%.3f|%s' % (r['path'], pos[0], pos[1], pos[2], rgb[0], rgb[1], rgb[2], flags))
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', newline='\r\n') as f:
    f.write('# Zeppelin F-223A lamp catalog: light for world models that carry no M2 light (generated by\n'
            '# zpaks/zep-vulkan-shaders/lamp-catalog/gen_lamp_catalog.py from the stock client; edit the generator).\n'
            '# path|x|y|z (model space)|r|g|b (colour * intensity, stock fire = 0.47 0.29 0.13)|flags (f = flickers)\n')
    f.write('\n'.join(lines) + '\n')
print(len(lines), 'lamps ->', OUT)
