"""Shared definition of the F-074 + F-179 combined sectioned SQL file.

Both `cli/lib/creature/heroic.py` (F-074) and `cli/lib/item/scaler_existing.py`
(F-179 loot wiring) write to this file via the sectioned_sql helper. F-074
owns the F-074_heroic_creatures section (creature clones + base loot
inheritance + cache refs); F-179 owns the F-179_*_loot sections (UPDATEs
that swap stock items with their scaled F-179 entries on the clone loot
tables).

Apply order is enforced by section order INSIDE the file — F-074 first
(DELETE+INSERT base loot into clone lootids), F-179 second (UPDATE
stock→scaled on the rows F-074 just inserted). The whole file applies as
one unit, so whenever either section changes the file's hash changes and
`sql changed` re-runs the lot.

Why combined: F-074's reapply resets the clone loot tables (DELETE then
INSERT SELECT FROM base_lootid). F-179's UPDATEs then need to re-apply to
re-swap. As a separate file with stable hash, F-179 wouldn't be picked
up by `sql changed` after a F-074 reapply. Sectioning makes the
dependency invisible to the apply tracker — one file, one hash, one apply.
"""
from pathlib import Path

# Combined file lives in zep-dungeons sql/. Was previously two files:
#   zz_[AUTO,F-074]_heroic_convertor.sql   (deleted 2026-05-30)
#   zz_[AUTO,F-179]_azeroth_dungeon_loot.sql (deleted 2026-05-30)
COMBINED_FILENAME = "zz_[AUTO,F-074+F-179]_heroic_creature_loot.sql"

# Sections in apply order. F-074 always first (rebuilds clone loot from
# scratch); F-179 per-tier sections follow (each tier's UPDATEs are
# independent). Add F-179_outland_loot / F-179_northrend_loot here when
# those tiers come online.
SECTION_F074 = "F-074_heroic_creatures"
SECTION_F179_AZEROTH = "F-179_azeroth_loot"

SECTION_ORDER = (
    SECTION_F074,
    SECTION_F179_AZEROTH,
)

FILE_HEADER = """\
-- =========================================================================
-- Combined F-074 + F-179 heroic/mythic creature loot chain (auto-generated)
-- -------------------------------------------------------------------------
-- DO NOT EDIT BY HAND. Each section is regenerated by its owning command:
--   F-074_heroic_creatures   →  zep world creature heroic
--   F-179_azeroth_loot       →  zep world item scale-existing --tier azeroth
--
-- Apply order matters: F-074 section DELETEs+INSERTs base loot into clone
-- lootids; F-179 sections UPDATE those rows to swap stock items with their
-- scaled F-179 entries. The whole file applies as one unit so the apply
-- tracker correctly re-runs both whenever either changes.
-- =========================================================================
"""


def combined_path(craft_root: Path) -> Path:
    """Resolve the combined file's path under craft_root."""
    return craft_root / "zpaks" / "zep-dungeons" / "sql" / COMBINED_FILENAME
