"""F-216 layer 3 outfits -> F-198 wardrobe manifests.

A display customised with an outfit (retail item ids per slot) becomes a `kind: unique`
manifest in zep-npc-wardrobe/outfits/custom_<display>.json; `zep wardrobe build` then
imports the items, composites the new NPC bake and emits the display rows. New display
ids come from 900500-900999 (free). A creature is repointed only when its whole model
list is this one display (the wardrobe owns a creature's full list); others are reported.
"""
import json
from pathlib import Path
from typing import Dict, List, Tuple

ID_RANGE = (900500, 900999)
LOOK = ('skin_color', 'face_type', 'hair_style', 'hair_color', 'facial_hair')


def write_manifests(outfits: Dict[str, dict], customs: Dict[str, dict], result: dict,
                    creature_models: Dict[int, List[int]], outfit_dir: Path) -> Tuple[List[str], List[str]]:
    """-> (manifest files written, notes)."""
    outfit_dir.mkdir(parents=True, exist_ok=True)
    taken = set()
    for f in outfit_dir.glob('*.json'):
        try:
            taken |= set(json.loads(f.read_text()).get('display_ids', []))
        except Exception:
            pass
    cdi = result['effective_dbc'][0]
    cdx = result['effective_char_dbc'][0]
    written, notes = [], []
    keep = set()
    for did_s, items in sorted(outfits.items(), key=lambda kv: int(kv[0])):
        did = int(did_s)
        path = outfit_dir / f'custom_{did}.json'
        keep.add(path.name)
        old = json.loads(path.read_text()) if path.exists() else {}
        new_id = (old.get('display_ids') or [None])[0]
        if new_id is None:
            new_id = next(i for i in range(*ID_RANGE) if i not in taken)
        taken.add(new_id)
        ext = int((cdi.get(did) or {}).get('extended_display_info_id') or 0)
        x = cdx.get(ext)
        if not x:
            notes.append(f'display {did}: not a character display, outfit skipped')
            continue
        look = {k: int(x.get(k) or 0) for k in LOOK}
        cu = customs.get(did_s) or {}
        for k in ('hair_style', 'facial_hair'):
            if k in cu:
                look[k] = int(cu[k])
        creatures = [{'entry': e, 'displays': [new_id]} for e, ds in sorted(creature_models.items()) if ds == [did]]
        shared = [e for e, ds in creature_models.items() if did in ds and ds != [did]]
        if shared:
            notes.append(f'display {did}: creatures {shared[:6]} use it among other models - '
                         f'not repointed; add display {new_id} to them yourself')
        m = {'task': 'F-216', 'name': f'custom_{did}', 'kind': 'unique', 'race': int(x.get('race') or 0),
             '_comment': f'Generated by `zep model curate --apply` from the model-viewer customisation of display {did}. '
                         f'Edit the outfit in the picker (Customise tab), not here.',
             'outfit': {'items': {k: int(v) for k, v in items.items()}},
             'appearance': look, 'base_display': {str(int(x.get('gender') or 0)): did},
             'display_ids': [new_id], 'creatures': creatures}
        text = json.dumps(m, indent=2) + '\n'
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            written.append(path.name)
    for f in outfit_dir.glob('custom_*.json'):
        if f.name not in keep:
            f.unlink()
            notes.append(f'removed {f.name} (customisation cleared)')
    return written, notes
