"""
SQL generation functions for starting weapons system.

Generates SQL files into the F-022 zpak:
  - dbc/[AUTO,F-022]_skillraceclassinfo.sql  (DBC: trainer skill availability)
  - sql/zz_[AUTO,F-022]_starting_weapon_skills.sql  (World: character creation skills)
  - dbc/[AUTO,F-022]_charstartoutfit.sql  (DBC: weapon fixes + display fixes)
  - csv_vs_stock_wotlk.log  (Documentation only, not in zpak)
"""

import os
import click

from .spreadsheet_reader import read_weapon_class_masks
from .constants import WEAPON_SKILLS, SKILL_TO_INVTYPE, STARTER_AMMO


def generate_skillraceclassinfo_sql(spreadsheet_path, dbc_dir):
    """
    Generate skillraceclassinfo SQL to make skills learnable by class.

    Args:
        spreadsheet_path: Path to the Race and Class Masks.xlsx file
        dbc_dir: Zpak dbc/ directory for output
    """
    click.echo("=" * 80)
    click.echo("GENERATING SKILL RACE CLASS INFO SQL")
    click.echo("=" * 80)
    click.echo()

    # Read weapon class masks from spreadsheet
    weapon_class_data = read_weapon_class_masks(spreadsheet_path)

    sql_lines = []

    # Header
    sql_lines.append("-- " + "=" * 76)
    sql_lines.append("-- SKILL RACE CLASS INFO - WEAPON SKILL AVAILABILITY")
    sql_lines.append("-- " + "=" * 76)
    sql_lines.append("-- This file controls which weapon skills are LEARNABLE by CLASS.")
    sql_lines.append("-- All races (raceMask=4095) can learn if their class allows it.")
    sql_lines.append("-- Must be applied BEFORE starting_weapon_skills.sql")
    sql_lines.append("--")
    sql_lines.append("-- AUTO-GENERATED by: zep outfit fix")
    sql_lines.append("-- DO NOT EDIT MANUALLY - Changes will be overwritten")
    sql_lines.append("-- " + "=" * 76)
    sql_lines.append("")

    # Delete existing weapon skill entries
    all_skill_ids = sorted(weapon_class_data.keys())
    skill_id_list = ', '.join(str(sid) for sid in all_skill_ids)
    sql_lines.append("-- Delete existing weapon skill entries")
    sql_lines.append(f"DELETE FROM `skillraceclassinfo` WHERE `skill_id` IN ({skill_id_list});")
    sql_lines.append("")

    # Insert entries for each skill with explicit IDs
    entry_id = 1000
    for skill_id in all_skill_ids:
        data = weapon_class_data[skill_id]
        sql_lines.append(f"-- {data['name']} (skill {skill_id}) - classMask {data['class_mask']}")
        sql_lines.append(
            f"INSERT INTO `skillraceclassinfo` "
            f"(`id`, `skill_id`, `race_mask`, `class_mask`, `flags`, `min_level`, `skill_tier_id`, `skill_cost_id`) "
            f"VALUES ({entry_id}, {skill_id}, 4095, {data['class_mask']}, 128, 0, 0, 0);"
        )
        sql_lines.append("")
        entry_id += 1

    sql_content = '\n'.join(sql_lines)

    # Write to zpak dbc/ directory
    output_path = os.path.join(dbc_dir, '[AUTO,F-022]_skillraceclassinfo.sql')
    with open(output_path, 'w') as f:
        f.write(sql_content)

    click.echo(f"+ Generated {output_path}")
    click.echo(f"  {len(all_skill_ids)} weapon skills")
    click.echo()

    return sql_content


def generate_starting_skills_sql(weapon_skills, sql_dir):
    """
    Generate starting_weapon_skills SQL for character creation skills.

    Args:
        weapon_skills: Dict from read_weapon_skills_from_spreadsheet()
        sql_dir: Zpak sql/ directory for output
    """
    click.echo("=" * 80)
    click.echo("GENERATING WEAPON SKILLS SQL")
    click.echo("=" * 80)
    click.echo()

    sql_lines = []

    # Header
    sql_lines.append("-- " + "=" * 76)
    sql_lines.append("-- STARTING WEAPON SKILLS")
    sql_lines.append("-- " + "=" * 76)
    sql_lines.append("-- This file controls which races can use which weapon types at character")
    sql_lines.append("-- creation. All weapon skill changes should be made in this file ONLY.")
    sql_lines.append("--")
    sql_lines.append("-- AUTO-GENERATED by: zep outfit fix")
    sql_lines.append("-- DO NOT EDIT MANUALLY - Changes will be overwritten")
    sql_lines.append("--")
    sql_lines.append("-- RACE MASKS (add values for multiple races):")
    sql_lines.append("--   1 = Human       2 = Orc         4 = Dwarf       8 = Night Elf")
    sql_lines.append("--  16 = Undead     32 = Tauren     64 = Gnome     128 = Troll")
    sql_lines.append("-- 256 = Goblin    512 = Blood Elf  1024 = Draenei  2048 = Worgen")
    sql_lines.append("--   0 = None      4095 = All Races")
    sql_lines.append("--")
    sql_lines.append("-- CLASS MASKS (add values for multiple classes):")
    sql_lines.append("--   1 = Warrior     2 = Paladin      4 = Hunter      8 = Rogue     16 = Priest")
    sql_lines.append("--  32 = DK         64 = Shaman     128 = Mage      256 = Warlock  512 = (unused)")
    sql_lines.append("-- 1024 = Druid")
    sql_lines.append("--   0 = All       2047 = All Classes")
    sql_lines.append("-- " + "=" * 76)
    sql_lines.append("")

    # Delete existing weapon skills
    sql_lines.append("-- Delete existing weapon skills")
    all_skill_ids = sorted(weapon_skills.keys())
    skill_id_list = ', '.join(str(sid) for sid in all_skill_ids)
    sql_lines.append(f"DELETE FROM `playercreateinfo_skills` WHERE `skill` IN ({skill_id_list});")
    sql_lines.append("")

    # Group by weapon category
    weapon_categories = {
        'ONE-HANDED WEAPONS': [43, 44, 54, 173],
        'TWO-HANDED WEAPONS': [55, 160, 172, 136, 229],
        'RANGED WEAPONS': [45, 46, 47, 176, 228],
        'OTHER': [162, 433, 473]
    }

    for category, skill_ids in weapon_categories.items():
        category_has_skills = any(sid in weapon_skills for sid in skill_ids)
        if not category_has_skills:
            continue

        sql_lines.append("-- " + "=" * 76)
        sql_lines.append(f"-- {category}")
        sql_lines.append("-- " + "=" * 76)
        sql_lines.append("")

        for skill_id in skill_ids:
            if skill_id not in weapon_skills:
                continue

            data = weapon_skills[skill_id]
            sql_lines.append(f"-- {data['name']} (skill {skill_id})")

            for cls in data['classes']:
                comment = f"{cls['name']} - {data['name']}"
                comment_escaped = comment.replace("'", "''")
                sql_lines.append(f"INSERT INTO `playercreateinfo_skills` (`raceMask`, `classMask`, `skill`, `rank`, `comment`) VALUES ({cls['race_mask']}, {cls['class_mask']}, {skill_id}, 0, '{comment_escaped}');")

            sql_lines.append("")

    sql_content = '\n'.join(sql_lines)

    # Write to zpak sql/ directory
    output_path = os.path.join(sql_dir, 'zz_[AUTO,F-022]_starting_weapon_skills.sql')
    with open(output_path, 'w') as f:
        f.write(sql_content)

    click.echo(f"+ Generated {output_path}")
    click.echo(f"  {len(all_skill_ids)} weapon skills")
    click.echo(f"  {sum(len(data['classes']) for data in weapon_skills.values())} total class entries")
    click.echo()

    return sql_content


def generate_starting_ammo_sql(dbc_cursor, sql_dir, amount=2000):
    """
    Generate playercreateinfo_item entries for starting ammo.

    Scans the live DBC charstartoutfit for all outfits with ammo slots
    (inventory_type=24) and generates INSERT statements so hunters start
    with a full stack instead of the default 200.

    Args:
        dbc_cursor: Cursor for the live dbc database (after weapon fixes applied)
        sql_dir: Zpak sql/ directory for output
        amount: Ammo quantity to give (default 2000)
    """
    click.echo("=" * 80)
    click.echo("GENERATING STARTING AMMO SQL")
    click.echo("=" * 80)
    click.echo()

    from .constants import RACE_NAMES, CLASS_NAMES

    # Find all outfits that have ammo (inventory_type=24) in any slot
    invtype_cols = ', '.join(f'inventory_type_{i}' for i in range(1, 25))
    item_cols = ', '.join(f'item_{i}' for i in range(1, 25))
    dbc_cursor.execute(f"""
        SELECT race, class, gender, {item_cols}, {invtype_cols}
        FROM charstartoutfit
        WHERE race BETWEEN 1 AND 12 AND class BETWEEN 1 AND 11
        ORDER BY race, class, gender
    """)

    # Collect ammo items per (race, class) - deduplicate across genders
    ammo_by_race_class = {}
    for row in dbc_cursor.fetchall():
        race_id, class_id, gender = row[0], row[1], row[2]
        items = row[3:27]
        invtypes = row[27:51]

        for i in range(24):
            if invtypes[i] == 24 and items[i] and items[i] > 0:
                key = (race_id, class_id)
                ammo_by_race_class[key] = items[i]
                break  # One ammo type per outfit

    if not ammo_by_race_class:
        click.echo("No outfits with ammo found - skipping")
        click.echo()
        return ""

    # Build ammo item lookup for comments
    ammo_items = set(ammo_by_race_class.values())

    sql_lines = []
    sql_lines.append("-- " + "=" * 76)
    sql_lines.append("-- STARTING AMMO QUANTITIES")
    sql_lines.append("-- " + "=" * 76)
    sql_lines.append(f"-- Gives hunters {amount} ammo at character creation instead of default 200.")
    sql_lines.append("-- Ammo type matches each outfit's ranged weapon (arrows for bows, shots for guns).")
    sql_lines.append("--")
    sql_lines.append("-- AUTO-GENERATED by: zep outfit fix")
    sql_lines.append("-- DO NOT EDIT MANUALLY - Changes will be overwritten")
    sql_lines.append("-- " + "=" * 76)
    sql_lines.append("")

    # Delete existing ammo entries
    ammo_id_list = ', '.join(str(a) for a in sorted(ammo_items))
    sql_lines.append("-- Delete existing starting ammo entries")
    sql_lines.append(f"DELETE FROM `playercreateinfo_item` WHERE `itemid` IN ({ammo_id_list});")
    sql_lines.append("")

    # Generate inserts grouped by race
    for (race_id, class_id), ammo_item in sorted(ammo_by_race_class.items()):
        race_name = RACE_NAMES.get(race_id, f'Race {race_id}')
        class_name = CLASS_NAMES.get(class_id, f'Class {class_id}')
        ammo_name = 'Rough Arrow' if ammo_item == 2512 else 'Light Shot' if ammo_item == 2516 else f'Item {ammo_item}'
        sql_lines.append(f"-- {race_name} {class_name}: {ammo_name} x{amount}")
        sql_lines.append(
            f"INSERT INTO `playercreateinfo_item` (`race`, `class`, `itemid`, `amount`) "
            f"VALUES ({race_id}, {class_id}, {ammo_item}, {amount});"
        )

    sql_lines.append("")
    sql_content = '\n'.join(sql_lines)

    # Append to the existing starting weapon skills file
    output_path = os.path.join(sql_dir, 'zz_[AUTO,F-022]_starting_weapon_skills.sql')
    with open(output_path, 'a') as f:
        f.write('\n\n' + sql_content)

    click.echo(f"+ Appended {len(ammo_by_race_class)} ammo entries to {output_path}")
    click.echo(f"  Amount: {amount} per hunter")
    click.echo()

    return sql_content


def generate_weapon_fixes_sql(mismatches, weapon_additions, invtype_fixes, duplicate_cleanups,
                              dbc_dir, output_mode='sql', log_dir=None):
    """
    Generate charstartoutfit weapon fixes SQL or documentation log.

    Args:
        mismatches: List of weapon mismatch/replacement entries
        weapon_additions: List of weapons to add
        invtype_fixes: List of inventory_type_ corrections
        duplicate_cleanups: List of duplicate weapons to remove
        dbc_dir: Zpak dbc/ directory for SQL output
        output_mode: 'sql' for SQL fixes (current DB), 'log' for documentation
        log_dir: Directory for log output (used when output_mode='log')
    """
    click.echo("=" * 80)
    if output_mode == 'log':
        click.echo("GENERATING CSV vs STOCK WOTLK DOCUMENTATION LOG")
    else:
        click.echo("GENERATING STARTING WEAPONS SQL")
    click.echo("=" * 80)
    click.echo()

    sql_lines = []

    # Combine and sort all fixes by outfit_id
    all_fixes = []

    for mismatch in mismatches:
        all_fixes.append({
            'outfit_id': mismatch['outfit_id'],
            'race': mismatch['race'],
            'class': mismatch['class'],
            'gender': mismatch['gender'],
            'slot': mismatch['slot'],
            'type': 'replace',
            'data': mismatch
        })

    for addition in weapon_additions:
        all_fixes.append({
            'outfit_id': addition['outfit_id'],
            'race': addition['race'],
            'class': addition['class'],
            'gender': addition['gender'],
            'slot': addition['slot'],
            'type': 'add',
            'data': addition
        })

    # Sort by outfit_id, then by slot
    all_fixes.sort(key=lambda x: (x['outfit_id'], x['slot']))

    # Generate SQL for each fix
    for fix in all_fixes:
        slot = fix['slot']
        outfit_id = fix['outfit_id']

        if fix['type'] == 'replace':
            mismatch = fix['data']
            action = mismatch.get('action', 'replace')

            if mismatch.get('slot_mismatch'):
                target_slot = mismatch['target_slot']
                skill_name = next((name for sid, name in WEAPON_SKILLS.values() if sid == mismatch['replacement_skill']), "Unknown")
                inv_type = SKILL_TO_INVTYPE.get(mismatch['replacement_skill'], 13)

                sql_lines.append(f"-- {mismatch['race']} {mismatch['class']} ({mismatch['gender']}): Move {skill_name} from slot {slot} to slot {target_slot} (stock WOTLK position)")
                sql_lines.append(f"UPDATE `charstartoutfit` SET `item_{slot}` = 0, `inventory_type_{slot}` = 0 WHERE `id` = {outfit_id};")
                sql_lines.append(f"UPDATE `charstartoutfit` SET `item_{target_slot}` = {mismatch['replacement_item']}, `inventory_type_{target_slot}` = {inv_type} WHERE `id` = {outfit_id};")
            elif action == 'remove' or mismatch['replacement_item'] == 0:
                reason = mismatch.get('reason', 'no suitable replacement')
                sql_lines.append(f"-- {mismatch['race']} {mismatch['class']} ({mismatch['gender']}): Remove {mismatch['current_type']} ({reason})")
                sql_lines.append(f"UPDATE `charstartoutfit` SET `item_{slot}` = 0, `inventory_type_{slot}` = 0 WHERE `id` = {outfit_id};")
            else:
                skill_name = next((name for sid, name in WEAPON_SKILLS.values() if sid == mismatch['replacement_skill']), "Unknown")
                reason = mismatch.get('reason', f'Replace {mismatch["current_type"]} with {skill_name}')
                sql_lines.append(f"-- {mismatch['race']} {mismatch['class']} ({mismatch['gender']}): {reason}")
                sql_lines.append(f"UPDATE `charstartoutfit` SET `item_{slot}` = {mismatch['replacement_item']} WHERE `id` = {outfit_id};")
            sql_lines.append("")
        else:  # add
            addition = fix['data']
            if addition.get('is_ammo'):
                sql_lines.append(f"-- {addition['race']} {addition['class']} ({addition['gender']}): Add {addition['reason']}")
                sql_lines.append(f"UPDATE `charstartoutfit` SET `item_{slot}` = {addition['add_item']}, `inventory_type_{slot}` = 24 WHERE `id` = {outfit_id};")
            else:
                skill_name = next((name for sid, name in WEAPON_SKILLS.values() if sid == addition['add_skill']), "Unknown")
                inv_type = SKILL_TO_INVTYPE.get(addition['add_skill'], 13)
                sql_lines.append(f"-- {addition['race']} {addition['class']} ({addition['gender']}): Add {skill_name} ({addition['reason']})")
                sql_lines.append(f"UPDATE `charstartoutfit` SET `item_{slot}` = {addition['add_item']}, `inventory_type_{slot}` = {inv_type} WHERE `id` = {outfit_id};")
            sql_lines.append("")

    # SECTION: Cleanup duplicates
    if duplicate_cleanups:
        sql_lines.append("-- " + "=" * 76)
        sql_lines.append("-- CLEANUP: REMOVE DUPLICATE WEAPONS/AMMO")
        sql_lines.append("-- " + "=" * 76)
        sql_lines.append("")

        for cleanup in duplicate_cleanups:
            reason = cleanup.get('reason', 'Duplicate weapon/ammo')
            sql_lines.append(f"-- {cleanup['race']} {cleanup['class']} ({cleanup['gender']}): {reason}")
            sql_lines.append(f"UPDATE `charstartoutfit` SET `item_{cleanup['slot']}` = 0, `inventory_type_{cleanup['slot']}` = 0 WHERE `id` = {cleanup['outfit_id']};")

        sql_lines.append("")
        sql_lines.append(f"-- Cleaned up {len(duplicate_cleanups)} duplicate weapons/ammo")
        sql_lines.append("")

    # Write to file
    if output_mode == 'log':
        out = log_dir if log_dir else dbc_dir
        output_path = os.path.join(out, 'csv_vs_stock_wotlk.log')

        log_lines = []
        log_lines.append("=" * 80)
        log_lines.append("CSV WEAPON SKILLS vs STOCK WOTLK COMPARISON")
        log_lines.append("=" * 80)
        log_lines.append("")
        log_lines.append("This file documents the intentional differences between our custom")
        log_lines.append("weapon skill system (defined in CSV) and stock WOTLK starting weapons.")
        log_lines.append("")
        log_lines.append("These differences are BY DESIGN and represent our custom game balance.")
        log_lines.append("This is NOT a list of bugs - it's documentation of intended changes.")
        log_lines.append("")
        log_lines.append("=" * 80)
        log_lines.append("UPDATE DIRECTION: STOCK WOTLK -> CSV REQUIREMENTS")
        log_lines.append("=" * 80)
        log_lines.append("")
        log_lines.append("The UPDATE statements show changes needed to align stock WOTLK with CSV.")
        log_lines.append("")
        log_lines.append("These UPDATEs are for DOCUMENTATION ONLY (explaining design decisions).")
        log_lines.append("Do NOT execute these - they would revert intentional changes!")
        log_lines.append("")
        log_lines.append("=" * 80)
        log_lines.append(f"FOUND {len(all_fixes)} INTENTIONAL DIFFERENCES FROM STOCK WOTLK")
        log_lines.append("=" * 80)
        log_lines.append("")

        log_lines.extend(sql_lines)

        with open(output_path, 'w') as f:
            f.write('\n'.join(log_lines))

        click.echo(f"+ Generated {output_path}")
        click.echo(f"  {len(all_fixes)} differences from stock WOTLK documented")
    else:
        output_path = os.path.join(dbc_dir, '[AUTO,F-022]_charstartoutfit.sql')

        # Preserve any existing tier set section
        preserved_tier = ""
        if os.path.exists(output_path):
            with open(output_path, 'r') as f:
                old_content = f.read()
            from .tier_sets import TIER_SECTION_START, TIER_SECTION_END
            start = old_content.find(TIER_SECTION_START)
            if start >= 0:
                end = old_content.find(TIER_SECTION_END)
                if end >= 0:
                    preserved_tier = old_content[start:end + len(TIER_SECTION_END)]

        with open(output_path, 'w') as f:
            f.write('\n'.join(sql_lines))
            if preserved_tier:
                f.write('\n\n\n' + preserved_tier + '\n')

        click.echo(f"+ Generated {output_path}")
        click.echo(f"  {len(mismatches)} weapon replacements")
        click.echo(f"  {len(weapon_additions)} weapon additions")
        if duplicate_cleanups:
            click.echo(f"  {len(duplicate_cleanups)} duplicates cleaned")
        if preserved_tier:
            click.echo("  (preserved existing tier set section)")

    click.echo()

    return '\n'.join(sql_lines)


def generate_display_info_fixes_sql(display_mismatches, dbc_dir):
    """
    Generate SQL to fix display_item_ mismatches in charstartoutfit.

    Appends to the existing [AUTO,F-022]_charstartoutfit.sql file.

    Args:
        display_mismatches: List from validate_display_info()
        dbc_dir: Zpak dbc/ directory containing the charstartoutfit SQL file

    Returns:
        str: SQL statements, or empty string if no fixes needed
    """
    if not display_mismatches:
        click.echo("No display_item_ fixes needed")
        click.echo()
        return ""

    click.echo("=" * 80)
    click.echo("GENERATING DISPLAY INFO FIXES SQL")
    click.echo("=" * 80)
    click.echo()

    sql_lines = []

    sql_lines.append("-- " + "=" * 76)
    sql_lines.append("-- DISPLAY INFO FIXES")
    sql_lines.append("-- " + "=" * 76)
    sql_lines.append("-- Fixes display_item_ values that don't match item_template.displayid")
    sql_lines.append("-- The client uses display_item_ for character creation preview models")
    sql_lines.append("-- " + "=" * 76)
    sql_lines.append("")

    for mismatch in display_mismatches:
        slot = mismatch['slot']
        sql_lines.append(
            f"-- {mismatch['race']} {mismatch['class']} ({mismatch['gender']}): "
            f"Fix {mismatch['item_name']} display_item_ {mismatch['current_display']} -> {mismatch['correct_display']}"
        )
        sql_lines.append(
            f"UPDATE `charstartoutfit` SET `display_item_{slot}` = {mismatch['correct_display']} "
            f"WHERE `id` = {mismatch['outfit_id']};"
        )
        sql_lines.append("")

    sql_content = '\n'.join(sql_lines)

    # Append to [AUTO,F-022]_charstartoutfit.sql (before tier section if present)
    output_path = os.path.join(dbc_dir, '[AUTO,F-022]_charstartoutfit.sql')

    existing_content = ""
    preserved_tier = ""
    if os.path.exists(output_path):
        with open(output_path, 'r') as f:
            existing_content = f.read()

        # Extract tier section so we can re-append it at the end
        from .tier_sets import TIER_SECTION_START, TIER_SECTION_END
        start = existing_content.find(TIER_SECTION_START)
        if start >= 0:
            end = existing_content.find(TIER_SECTION_END)
            if end >= 0:
                preserved_tier = existing_content[start:end + len(TIER_SECTION_END)]
                existing_content = existing_content[:start].rstrip()

    with open(output_path, 'w') as f:
        if existing_content.strip():
            f.write(existing_content.rstrip() + "\n\n\n")
        f.write(sql_content)
        if preserved_tier:
            f.write('\n\n\n' + preserved_tier + '\n')

    click.echo(f"+ Added {len(display_mismatches)} display_item_ fixes to {output_path}")
    click.echo()

    return sql_content
