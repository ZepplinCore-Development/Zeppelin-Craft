"""F-028 Phase 3 — loot table generator.

Reads `data/relic_effects.json` (relic_plan + dungeon_bosses) and emits
`zpaks/zep-items/sql/zz_[F-028]_loot.sql` — idempotent `creature_loot_template`
rows binding each relic to its assigned boss.

Re-run after editing `relic_effects.json` (boss assignments or drop chance):
    python3 -m cli.lib.item.relic_loot_generator

Then apply:
    zep world sql changed
"""

import json
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[3]
DATA = PROJECT_ROOT / "cli" / "lib" / "item" / "data" / "relic_effects.json"
SQL_OUT = PROJECT_ROOT / "zpaks" / "zep-items" / "sql" / "zz_[F-028]_loot.sql"


def pair_relics_with_bosses(plan: dict, dungeon_bosses: dict) -> list[dict]:
    """For each relic entry in plan order, attach (boss_name, boss_id) by
    matching dungeon name and tracking which slot (a or b) we've filled."""
    rows = []
    slot_idx = {}  # dungeon -> 0 (next: boss_a) or 1 (next: boss_b)
    for band in ("level_band_20_30", "level_band_30_40", "level_band_40_50", "level_band_50_60"):
        for entry in plan[band]:
            dungeon = entry["dungeon"]
            if dungeon not in dungeon_bosses:
                raise ValueError(f"No boss assignment for dungeon: {dungeon}")
            idx = slot_idx.get(dungeon, 0)
            slot_idx[dungeon] = idx + 1
            bosses = dungeon_bosses[dungeon]
            if idx == 0:
                boss_name, boss_id = bosses["boss_a"]
            elif idx == 1:
                boss_name, boss_id = bosses["boss_b"]
            else:
                raise ValueError(f"More than 2 relics planned for {dungeon}")
            rows.append({
                "dungeon": dungeon,
                "level_band": band.replace("level_band_", "").replace("_", "-"),
                "boss_name": boss_name,
                "boss_id": boss_id,
                "relic_name": entry["name_hint"],
                "item_id": entry["item_id"],
                "spell_id": entry["spell_id"],
                "item_class": entry["class"],
                "req_level": entry["req_level"],
                "ilvl": entry["ilvl"],
                "quality": 2 if entry["req_level"] < 30 else 3,
                "effect": entry["effect"],
                "target_spell": entry["target"],
            })
    return rows


def write_loot_sql(rows: list[dict], drop_chance: float) -> None:
    blocks = [
        "-- F-028 Low-Level Relic Slot Drops — creature_loot_template wiring (Phase 3)",
        "-- 52 relic entries (59039-59090) bound to dungeon bosses, 10% chance each.",
        "-- Generated by cli/lib/item/relic_loot_generator.py from data/relic_effects.json.",
        "-- Idempotent: DELETE row for (Entry, Item) before INSERT.",
        "",
    ]
    # Group rows by boss for tidier output
    by_boss: dict[int, list[dict]] = {}
    for r in rows:
        by_boss.setdefault(r["boss_id"], []).append(r)

    for boss_id in sorted(by_boss):
        boss_rows = by_boss[boss_id]
        boss_name = boss_rows[0]["boss_name"]
        dungeon = boss_rows[0]["dungeon"]
        blocks.append(f"-- {boss_name} (entry {boss_id}, {dungeon})")
        for r in boss_rows:
            blocks.append(
                f"DELETE FROM `creature_loot_template` WHERE `Entry` = {boss_id} AND `Item` = {r['item_id']};"
            )
            comment = f"{r['relic_name']} (F-028 {r['item_class']} relic)".replace("'", "''")
            blocks.append(
                f"INSERT INTO `creature_loot_template` SET "
                f"`Entry` = {boss_id}, `Item` = {r['item_id']}, "
                f"`Reference` = 0, `Chance` = {drop_chance}, `QuestRequired` = 0, "
                f"`LootMode` = 1, `GroupId` = 0, `MinCount` = 1, `MaxCount` = 1, "
                f"`Comment` = '{comment}';"
            )
        blocks.append("")

    SQL_OUT.write_text("\n".join(blocks) + "\n")


def build() -> tuple[int, int, float]:
    d = json.loads(DATA.read_text())
    plan = d["relic_plan"]
    dungeon_bosses = {k: v for k, v in d["dungeon_bosses"].items() if not k.startswith("_")}
    drop_chance = float(d["dungeon_bosses"].get("_drop_chance_pct", 10.0))

    rows = pair_relics_with_bosses(plan, dungeon_bosses)
    write_loot_sql(rows, drop_chance)
    return len(rows), len({r["boss_id"] for r in rows}), drop_chance


if __name__ == "__main__":
    n_rows, n_bosses, drop_pct = build()
    print(f"SQL: {SQL_OUT} ({n_rows} loot bindings on {n_bosses} unique bosses)")
    print(f"Drop chance: {drop_pct}% across the board")
